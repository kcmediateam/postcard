// One-off: create (or reuse) Stripe test Products/Prices for our catalog and
// write the price-id map to src/lib/stripe/prices.ts. Idempotent via lookup_key.
//   node scripts/create-stripe-prices.mjs
import { readFileSync, writeFileSync } from "node:fs";
import Stripe from "stripe";

const env = {};
for (const line of readFileSync(new URL("../.env.local", import.meta.url), "utf8").split("\n")) {
  const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
  if (m) env[m[1]] = m[2];
}
const stripe = new Stripe(env.STRIPE_SECRET_KEY);

// [catalogId, productName, credits, unitAmountCents, recurring?]
const PACKS = [
  ["pack_small", "Postcard credits — Small (100)", 100, 15900, false],
  ["pack_medium", "Postcard credits — Medium (250)", 250, 38500, false],
  ["pack_large", "Postcard credits — Large (500)", 500, 74500, false],
  ["pack_jumbo", "Postcard credits — Jumbo (1000)", 1000, 144000, false],
];
const PLANS = [
  ["plan_starter", "Starter — 250 credits/mo", 250, 36000, true],
  ["plan_growth", "Growth — 500 credits/mo", 500, 69500, true],
  ["plan_pro", "Pro — 1000 credits/mo", 1000, 134000, true],
  ["plan_scale", "Scale — 2500 credits/mo", 2500, 322500, true],
];

const ids = {};
for (const [catalogId, name, credits, amount, recurring] of [...PACKS, ...PLANS]) {
  const existing = await stripe.prices.list({ lookup_keys: [catalogId], active: true, limit: 1 });
  if (existing.data.length) {
    ids[catalogId] = existing.data[0].id;
    console.log(`reuse  ${catalogId} -> ${existing.data[0].id}`);
    continue;
  }
  const product = await stripe.products.create({
    name,
    metadata: { catalog_id: catalogId, credits: String(credits) },
  });
  const price = await stripe.prices.create({
    product: product.id,
    currency: "usd",
    unit_amount: amount,
    lookup_key: catalogId,
    metadata: { catalog_id: catalogId, credits: String(credits) },
    ...(recurring ? { recurring: { interval: "month" } } : {}),
  });
  ids[catalogId] = price.id;
  console.log(`create ${catalogId} -> ${price.id}`);
}

const body = `/**
 * Map of our catalog ids -> Stripe Price ids (test mode).
 * GENERATED by scripts/create-stripe-prices.mjs — do not edit by hand.
 */
export const STRIPE_PRICE_IDS: Record<string, string> = ${JSON.stringify(ids, null, 2)};

export function priceIdFor(catalogId: string): string | undefined {
  return STRIPE_PRICE_IDS[catalogId];
}
`;
writeFileSync(new URL("../src/lib/stripe/prices.ts", import.meta.url), body);
console.log("\nwrote src/lib/stripe/prices.ts");
